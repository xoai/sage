#!/usr/bin/env bash
# Install Sage's generated instructions into a file the USER may own (CLAUDE.md).
#
# WHY THIS EXISTS
#
# `sage init` and `sage update` used to write CLAUDE.md wholesale: a project's own
# rules vanished with no backup, and so did anything a user added to a CLAUDE.md
# Sage had written (review 2026-10-26, C4). Opencode's generator skips a user's
# AGENTS.md instead — but on Claude Code that leaves Sage installed with no
# instructions at all. So Sage's text lives in a marked block, and Sage only ever
# rewrites what is between the markers:
#
#   no file                       → the block alone
#   exactly one BEGIN, then END   → that block replaced, everything else kept
#   no markers, Sage's own legacy → backed up once under .sage/backups/, then the
#     whole-file layout             block alone (the one-time move to markers)
#   no markers, the user's file   → kept line for line, block appended at the end
#   markers malformed (one        → file left untouched, with a warning: guessing
#     missing, repeated, reversed)  which lines are ours could delete the user's
#
# Line endings: markers match with or without a trailing CR, and a CRLF file
# gets a CRLF block, so a Windows checkout does not grow a second block per update.
# The file is rewritten in place (`cat >`), never moved over, so a CLAUDE.md that
# is a symlink (`ln -s AGENTS.md CLAUDE.md`) stays one and its mode is kept.
#
# Usage:
#   source runtime/platforms/_shared/managed-md.sh
#   install_managed_md "$SAGE_ROOT/CLAUDE.md" "$generated" "$SAGE_ROOT/.sage/backups"
# Prints one status line. Always returns 0: a CLAUDE.md it declines to touch is a
# warning, not a reason to abort the rest of the generator.

# "Sage" must appear on the BEGIN line: platform detection (bin/sage
# select_platform, sage_platforms.detect_claude_code) recognizes a Sage-generated
# CLAUDE.md by "Sage" on its first line.
SAGE_MD_BEGIN="<!-- BEGIN SAGE — generated by Sage (sage init / sage update). Edits inside this block are overwritten; edit outside it. -->"
SAGE_MD_END="<!-- END SAGE -->"
SAGE_MD_LEGACY_HEAD="# Sage — Project Instructions"

# _sage_md_block <generated> <crlf:true|false> — the block, markers included.
_sage_md_block() {
  { printf '%s\n' "$SAGE_MD_BEGIN"; cat "$1"; printf '%s\n' "$SAGE_MD_END"; } \
    | if [ "$2" = true ]; then awk '{ sub(/\r$/, ""); printf "%s\r\n", $0 }'; else cat; fi
}

install_managed_md() {
  local dest="$1" generated="$2" backup_dir="$3"
  local name; name=$(basename "$dest")
  local tmp="${generated}.managed"

  if [ ! -e "$dest" ]; then
    _sage_md_block "$generated" false > "$dest"
    echo "  ✓ $name"
    return 0
  fi

  local crlf=false
  if head -1 "$dest" | grep -q $'\r$'; then crlf=true; fi

  # Marker line numbers, CR-insensitive. `|| true`: no match is a normal answer,
  # and under `set -e` a failing substitution would abort the generator.
  local begins ends
  begins=$(tr -d '\r' < "$dest" | grep -nxF "$SAGE_MD_BEGIN" | cut -d: -f1 | tr '\n' ' ' || true)
  ends=$(tr -d '\r' < "$dest" | grep -nxF "$SAGE_MD_END" | cut -d: -f1 | tr '\n' ' ' || true)
  # shellcheck disable=SC2086  # deliberate word count
  set -- $begins; local nb=$# b1="${1:-0}"
  # shellcheck disable=SC2086
  set -- $ends; local ne=$# e1="${1:-0}"

  if [ "$nb" -eq 1 ] && [ "$ne" -eq 1 ] && [ "$b1" -lt "$e1" ]; then
    _sage_md_block "$generated" "$crlf" > "$tmp"
    awk -v b="$b1" -v e="$e1" -v blk="$tmp" '
      NR == b { while ((getline l < blk) > 0) print l }
      NR >= b && NR <= e { next }
      { print }
    ' "$dest" > "${tmp}.out"
    cat "${tmp}.out" > "$dest"
    rm -f "$tmp" "${tmp}.out"
    echo "  ✓ $name (Sage block refreshed; the rest of the file kept)"
  elif [ "$nb" -eq 0 ] && [ "$ne" -eq 0 ]; then
    if head -1 "$dest" | tr -d '\r' | grep -qxF "$SAGE_MD_LEGACY_HEAD"; then
      # Sage wrote this whole file before markers existed. Anything the user
      # added to it cannot be told apart from Sage's text, so keep a copy.
      local backup
      backup="$backup_dir/$name.$(date +%Y%m%d-%H%M%S).bak"
      mkdir -p "$backup_dir"
      cp "$dest" "$backup"
      _sage_md_block "$generated" "$crlf" > "$dest"
      echo "  ✓ $name (moved to a marked Sage block; previous file saved to $backup)"
    else
      local nl='\n'
      [ "$crlf" = true ] && nl='\r\n'
      { cat "$dest"
        if [ -s "$dest" ]; then
          # Keep the user's last line intact if the file lacks a final newline,
          # then one blank line between their text and the block.
          [ -n "$(tail -c1 "$dest")" ] && printf "$nl"
          printf "$nl"
        fi
        _sage_md_block "$generated" "$crlf"
      } > "$tmp"
      cat "$tmp" > "$dest"
      rm -f "$tmp"
      echo "  ✓ $name (your content kept; Sage's section is between the SAGE markers)"
    fi
  else
    echo "  ⚠ $name has malformed SAGE markers (BEGIN lines: ${begins:-none}; END lines: ${ends:-none})."
    echo "    Left untouched so none of your text is lost. Fix it to one BEGIN line"
    echo "    followed by one END line (or delete both), then run: sage update"
  fi
  return 0
}
